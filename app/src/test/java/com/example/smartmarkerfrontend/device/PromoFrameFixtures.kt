package com.example.smartmarkerfrontend.device

/** Same byte fixtures as CCU tests/ccu_protocol_test.cpp (gate G1). */
internal fun promoBytes(vararg parts: Any): ByteArray {
    val out = ArrayList<Byte>()
    for (part in parts) {
        when (part) {
            is Int -> {
                require(part in 0..255) { "fixture byte $part" }
                out.add(part.toByte())
            }
            is String -> part.encodeToByteArray().forEach { out.add(it) }
            else -> error("fixture part ${part.javaClass}")
        }
    }
    return out.toByteArray()
}

